	public Dipcoin generateDipcoin(final CustomerDipcoinRequest createReq, final User user,
			final CustomerAccount account, final Boolean isDuplicate) {

		Integer ttl = 0;

		// generate token + additional metadata
		String token = null;
		if(isDuplicate) {
			token = getUniqueToken(user);
		}else {
			token = CoreUtils.generateDipcoinToken();
		}
					
		LOG.debug(LogFormatter.instance(httpServletContext.getTraceId()).data("Phone", user.getPhone())
				.data("Coin", token).format());

		// create dipcoin in DB
		Dipcoin dcoin = new Dipcoin();
		dcoin.setUser(user);
		dcoin.setCoin(token);
		dcoin.setAmount(createReq.getAmount());
		dcoin.setCustomerAccount(account);
		dcoin.setUsageType(createReq.getUsageType());
		dcoin.setUsageCategory(createReq.getUsageCategory());
		if (!StringUtils.isEmpty(createReq.getUsageCategory()))
			dcoin.setUsageCategory(createReq.getUsageCategory());
		if (createReq.getUsageType() == null
				|| createReq.getUsageType() == DBConstants.DipcoinUsageType.GENERIC.value())
			dcoin.setUsageType(DBConstants.DipcoinUsageType.GENERIC.value());
		else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.ATM.value())
			dcoin.setUsageType(DBConstants.DipcoinUsageType.ATM.value());
		else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.TRANSFER.value())
			dcoin.setUsageType(DBConstants.DipcoinUsageType.TRANSFER.value());
		else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.BILL_PAYMENTS_RECHARGES.value())
			dcoin.setUsageType(DBConstants.DipcoinUsageType.BILL_PAYMENTS_RECHARGES.value());
		else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.PURCHASE.value())
			dcoin.setUsageType(DBConstants.DipcoinUsageType.PURCHASE.value());
		else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.RESTRICTED_BBPS_CASH.value())
          dcoin.setUsageType(DBConstants.DipcoinUsageType.RESTRICTED_BBPS_CASH.value());
		 else if (createReq.getUsageType() == DBConstants.DipcoinUsageType.RESTRICTED_BBPS_FUND_TRANSFER.value())
	          dcoin.setUsageType(DBConstants.DipcoinUsageType.RESTRICTED_BBPS_FUND_TRANSFER.value());
		
		dcoin.setClientTransactionId(httpServletContext.getClientTransactionId());

		Bank bank = account.getBank();

		// compute dipcoin TTL.
		if (DBConstants.DipcoinUsageType.TOLL.value() == createReq.getUsageType()
				|| DBConstants.BankType.VIRTUAL_BANK.value() == bank.getType()
				|| DBConstants.DipcoinUsageType.FEE.value() == createReq.getUsageType()
				|| DBConstants.DipcoinUsageType.DEPOSIT.value() == createReq.getUsageType()) {

			ttl = createReq.getTtlInHrs() != null
					? (createReq.getTtlInHrs() <= DBConstants.DIPCOIN_ONE_YEAR_TTL_HRS ? createReq.getTtlInHrs()
							: DBConstants.DIPCOIN_ONE_YEAR_TTL_HRS)
					: (account.getDipcoinExpiryTTL() > 0 ? account.getDipcoinExpiryTTL()
							: DBConstants.DIPCOIN_ONE_YEAR_TTL_HRS);

		} else {
			ttl = createReq.getTtlInHrs() != null
					? (createReq.getTtlInHrs() < DBConstants.DIPCOIN_MAX_TTL_HRS ? createReq.getTtlInHrs()
							: DBConstants.DIPCOIN_MAX_TTL_HRS)
					: (account.getDipcoinExpiryTTL() > 0 ? account.getDipcoinExpiryTTL()
							: DBConstants.DIPCOIN_MAX_TTL_HRS);
		}

		LOG.debug(LogFormatter.instance(httpServletContext.getTraceId()).data("UserTTL", createReq.getTtlInHrs())
				.data("AccountTTL", account.getDipcoinExpiryTTL()).data("FinalTTL", ttl).format());

		Dipcoin dipCoin = this.coinDBService.createCoin(dcoin, ttl);
		
		if(dipCoin == null) {
	        LOG.debug(LogFormatter.instance(httpServletContext.getTraceId()).message("Dipcoin Not Generated").format());
		} else {
		  LOG.debug(LogFormatter.instance(httpServletContext.getTraceId()).message("Dipcoin  Generated").format());
		}
		
		return dipCoin;
		
	}
 
 public Dipcoin generateDipcoin(final CustomerDipcoinRequest createReq, final Dipcoin dcoin,
			final CustomerAccount account) {
		Dipcoin coin = this.coinDBService.createCoin(dcoin,
				createReq.getTtlInHrs() != null ? createReq.getTtlInHrs() : account.getDipcoinExpiryTTL());
		return coin;
	}

	public String getUniqueToken(final User user) {
		// * Get Customer osta
		List<Dipcoin> existingDipcoin = this.coinDBService.getDipcoinByUserId(user.getId());
		if(existingDipcoin != null && existingDipcoin.size() > 0) {
			String coin = existingDipcoin.get(0).getCoin();
			Integer incrementCoin = Integer.getInteger(coin) + 1;
			return String.valueOf(incrementCoin);
		}
		return CoreUtils.generateDipcoinToken();
		
	}
	
		  
		  protected void saveFailureDipcoinTransaction(final DipcoinTransaction transaction,
			      HttpStatus status, HeaderCode code) {
			    try {
			      String now = String.valueOf(DateTime.now(DateTimeZone.UTC).getMillis());
			      LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
			          .message("Adding failure dipcoin transaction").data("transaction", transaction).format());
			      transaction.setDCResponseCode(String.valueOf(status.value()));
			      transaction.setDCResponseDesc(code.message());
			      transaction.setType(DipcoinTransactionType.VALIDATION_FAILURE.value());
			      transaction.setStatus(DipcoinTransactionsStatus.FAILURE.value());
			      transaction.setResponseTime(now);
			      transaction.setUpdateDate(now);

			      saveDipcoinTransaction(transaction);
			    } catch (Exception e) {
			      LOG.error(LogFormatter.instance(httpServletContext.getTraceId())
			          .message("Failed to add dipcoin transaction").format(), e);
			    }
			  }	  
		  
