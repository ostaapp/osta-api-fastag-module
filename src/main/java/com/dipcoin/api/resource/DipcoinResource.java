		  protected void saveDipcoinTransaction(final DipcoinTransaction transaction) {
		    try {
		      LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
		          .message("Adding dipcoin transaction").data("transaction", transaction).format());
		      // add transaction
		      DipcoinTransaction persisted = coinDBService.asyncAddTransaction(transaction).get();
		      if (persisted == null) {
		        LOG.error(LogFormatter.instance(httpServletContext.getTraceId())
		            .message("Failed to add dipcoin transaction").data("transaction", transaction)
		            .format());
		      } else {
		        LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
		            .message("Added dipcoin transaction").data("transaction", persisted).format());
		      }
		    } catch (Exception e) {
		      LOG.error(LogFormatter.instance(httpServletContext.getTraceId())
		          .message("Failed to add dipcoin transaction").format(), e);
		    }
		  }
		  
		  
		  protected void autogenerateDipcoin(final Dipcoin parent, final CustomerAccount account,
			      BigDecimal amount, TransactionSource source) {
			    LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
			        .data("DipcoinAutoGenerate", account.getDipcoinAutoGenerate()).data("amount", amount)
			        .data("ThresholdAmount", account.getThresholdAmount()).format());
			    if ((TransactionSource.TOLL.equals(source)
			        && BigDecimal.ONE.compareTo(amount) <= NumberUtils.INTEGER_ZERO)
			        || account.getDipcoinAutoGenerate() == BooleanStatus.YES.value()
			            && amount.compareTo(account.getThresholdAmount() != null ? account.getThresholdAmount()
			                : DBConstants.DIPCOIN_THRESHOLD_MIN_AMOUNT) > 0) {

			      AutoGenerateDipcoinRequest dReq = new AutoGenerateDipcoinRequest();
			      dReq.setCardId(account.getUserCardId());
			      dReq.setTtlInHrs(TransactionSource.TOLL.equals(source) ? DBConstants.DIPCOIN_ONE_YEAR_TTL_HRS
			          : account.getDipcoinExpiryTTL());
			      if (parent.getUsageType() == DBConstants.DipcoinUsageType.WALLET.value()) {
			        dReq.setTtlInHrs(DBConstants.DIPCOIN_ONE_YEAR_TTL_HRS);
			      }
			      dReq.setAmount(amount);
			      dReq.setParentDipcoinId(parent.getId());
			      dReq.setAccountId(account.getId());
			      dReq.setUsageType(parent.getUsageType());
			      dReq.setUsageCategory(parent.getUsageCategory());

			      LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
			          .message("Init Autogenerate request").data("Parent Dipcoin", parent.getCoin())
			          .data("DipcoinRequest", dReq).format());
			      
			      
			      try {
			        internalResource.autoGenerateDipcoin(account.getUser(), dReq, httpServletContext.getTraceId());
			      } catch (Exception e) {
			        
			        LOG.debug(LogFormatter.instance(httpServletContext.getTraceId())
			            .message("Init Autogenerate Exception").format(),e);
			      }

//			      AsyncRequest<DipcoinRequest> aReq = new AsyncRequest<>();
//			      aReq.setRawRequest(dReq);
//			      aReq.setUserId(account.getUser().getId());
//			      aReq.setTraceId(httpServletContext.getTraceId());
			            
			      //asyncRequestAmqpTemplate.convertAndSend(RabbitMqConfiguration.ASYNC_REQUEST_QUEUE, aReq);
			      dipcoinMetricRegistry.dipcoinAutoCreated().increment();

			    }
			  }
		  
